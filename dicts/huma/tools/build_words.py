#!/usr/bin/env python3
"""Build the Tigress word dictionaries and the validation report.

Inputs (all relative to the dicts/huma directory by default):
  tigress.dict.yaml, tigress_ci.dict.yaml, tigress_simp_ci.dict.yaml
  <repo>/build/rime/bin/opencc and <repo>/build/rime/share/opencc
  <repo>/build/SharedSupport/opencc/STCharacters_Tu.txt

Outputs:
  tigress_words_simp.dict.yaml
  tigress_words_trad.dict.yaml
  tigress_words_tradown.dict.yaml
  tools/words_report.txt
"""

import argparse
import hashlib
import re
import subprocess
import sys
import tempfile
from collections import Counter
from pathlib import Path

SCHEME = Path(__file__).resolve().parents[1]
REPO = SCHEME.parents[1]
REPORT = SCHEME / "tools/words_report.txt"
VERSION = "2026.10.22"

HEADER = """# Generated by tools/build_words.py; do not edit by hand.
name: {name}
version: "{version}"
sort: by_weight
use_preset_vocabulary: false
columns:
  - text
  - weight
  - code
  - stem
encoder:
  rules:
    - length_equal: 2
      formula: "AaAbBaBb"
    - length_equal: 3
      formula: "AaBaCaCb"
    - length_in_range: [4, 99]
      formula: "AaBaCaZa"

...
"""


def read_dict(path):
    rows, body = [], False
    for line in path.read_text(encoding="utf-8").splitlines():
        if line.strip() == "...":
            body = True
            continue
        if not body or not line.strip() or line.startswith("#"):
            continue
        parts = line.split("\t")
        if len(parts) < 3:
            continue
        text, weight, code = parts[0], parts[1], parts[2]
        try:
            rows.append((text, int(weight), code))
        except ValueError:
            continue
    return rows


def read_tu(path):
    mapping = {}
    for line in path.read_text(encoding="utf-8").splitlines():
        if not line.strip() or line.startswith("#"):
            continue
        parts = line.split("\t")
        if len(parts) < 2:
            continue
        mapping.setdefault(parts[0], set()).update(parts[1].split())
    return mapping


def char_codes(rows):
    codes = {}
    for text, _, code in rows:
        if len(text) != 1:
            continue
        # Longest code wins; on a tie the first occurrence is the primary form.
        if text not in codes or len(code) > len(codes[text]):
            codes[text] = code
    return codes


def encode(word, codes):
    try:
        if len(word) == 2:
            return (codes[word[0]][0] + codes[word[0]][1]
                    + codes[word[1]][0] + codes[word[1]][1])
        if len(word) == 3:
            return (codes[word[0]][0] + codes[word[1]][0]
                    + codes[word[2]][0] + codes[word[2]][1])
        if 4 <= len(word) <= 99:
            return (codes[word[0]][0] + codes[word[1]][0]
                    + codes[word[2]][0] + codes[word[-1]][0])
    except (KeyError, IndexError):
        return None
    return None


def convert_batch(opencc, config, texts, paths):
    input_text = "\n".join(texts) + "\n"
    command = [str(opencc), "-c", str(config)]
    for path in paths:
        command += ["--path", str(path)]
    result = subprocess.run(command, input=input_text, text=True,
                            capture_output=True)
    if result.returncode != 0:
        raise RuntimeError(f"opencc failed: {' '.join(command)}\n{result.stderr}")
    lines = result.stdout.splitlines()
    if len(lines) != len(texts):
        raise RuntimeError(f"opencc returned {len(lines)} lines for {len(texts)} inputs")
    return dict(zip(texts, lines))


def phrase_keys(opencc_dict, ocd2, directory):
    output = directory / (ocd2.stem + ".txt")
    result = subprocess.run(
        [str(opencc_dict), "-i", str(ocd2), "-o", str(output),
         "-f", "ocd2", "-t", "text"],
        capture_output=True, text=True)
    if result.returncode != 0:
        raise RuntimeError(f"opencc_dict failed for {ocd2}\n{result.stderr}")
    keys = set()
    for line in output.read_text(encoding="utf-8").splitlines():
        if line.strip():
            keys.add(line.split("\t", 1)[0])
    return keys


def write_dict(path, name, rows):
    lines = [HEADER.format(name=name, version=VERSION)]
    for text, weight, code in sorted(rows, key=lambda row: (-row[1], row[0], row[2])):
        lines.append(f"{text}\t{weight}\t{code}\n")
    with path.open("w", encoding="utf-8", newline="\n") as handle:
        handle.write("".join(lines))


def file_stats(path):
    data = path.read_bytes()
    return len(data), hashlib.sha256(data).hexdigest()


def append_list(lines, title, entries):
    lines.append(f"### {title} ({len(entries)})")
    lines.append("")
    if not entries:
        lines.append("- 无")
    else:
        lines.extend(f"- {entry}" for entry in entries)
    lines.append("")


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--opencc", type=Path,
                        default=REPO / "build/rime/bin/opencc")
    parser.add_argument("--opencc-data", type=Path,
                        default=REPO / "build/rime/share/opencc")
    parser.add_argument("--tu-table", type=Path,
                        default=REPO / "build/SharedSupport/opencc/STCharacters_Tu.txt")
    args = parser.parse_args()

    opencc = args.opencc.resolve()
    opencc_data = args.opencc_data.resolve()
    tu_table = args.tu_table.resolve()
    st_tu = tu_table.parent / "st_tu.json"
    opencc_dict = opencc.parent / "opencc_dict"

    for path in (opencc, tu_table, st_tu, opencc_dict,
                 opencc_data / "s2t.json", opencc_data / "t2s.json",
                 opencc_data / "STPhrases.ocd2", opencc_data / "TWPhrases.ocd2"):
        if not path.exists():
            parser.error(f"missing input: {path}")

    tigress = read_dict(SCHEME / "tigress.dict.yaml")
    ci = read_dict(SCHEME / "tigress_ci.dict.yaml")
    simp_ci = read_dict(SCHEME / "tigress_simp_ci.dict.yaml")

    codes = char_codes(tigress)
    tu = read_tu(tu_table)

    # Encoder self-check against the full-code ci table.
    encoder_bad = []
    for text, _, code in ci:
        if encode(text, codes) != code:
            encoder_bad.append(f"{text}: expected {code}, got {encode(text, codes)}")
    if encoder_bad:
        print(f"encoder self-check failed: {len(encoder_bad)} mismatches", file=sys.stderr)
        for item in encoder_bad[:20]:
            print(f"  {item}", file=sys.stderr)
        raise SystemExit(1)

    # Merge tigress_ci + tigress_simp_ci. A text may keep several codes; only
    # exact (text, code) duplicates are collapsed, keeping the larger weight.
    merged = {}
    for text, weight, code in ci + simp_ci:
        key = (text, code)
        if weight > merged.get(key, -1):
            merged[key] = weight
    simp_rows = [(text, weight, code) for (text, code), weight in merged.items()]
    simp_texts = sorted({text for text, _, _ in simp_rows})

    with tempfile.TemporaryDirectory(prefix="hufu-words-") as tmp:
        tmpdir = Path(tmp)
        trad_map = convert_batch(opencc, st_tu, simp_texts,
                                 [tu_table.parent, opencc_data])
        trad_texts = sorted(set(trad_map.values()))
        back_map = convert_batch(opencc, opencc_data / "t2s.json", trad_texts,
                                 [opencc_data])
        st_phrases = phrase_keys(opencc_dict, opencc_data / "STPhrases.ocd2", tmpdir)
        tw_phrases = phrase_keys(opencc_dict, opencc_data / "TWPhrases.ocd2", tmpdir)

    roundtrip_bad = [(text, trad_map[text], back_map[trad_map[text]])
                     for text in simp_texts
                     if back_map[trad_map[text]] != text]

    char_bad = []
    for text in simp_texts:
        trad = trad_map[text]
        if len(text) != len(trad):
            char_bad.append(f"{text} -> {trad}: length {len(text)} != {len(trad)}")
            continue
        for source, target in zip(text, trad):
            allowed = tu.get(source, {source})
            if target not in allowed:
                char_bad.append(f"{text} -> {trad}: {source} -> {target} not in {sorted(allowed)}")

    multi_chars = {char for char, targets in tu.items() if len(targets) > 1}
    risk = []
    for text in simp_texts:
        if not any(char in multi_chars for char in text):
            continue
        trad = trad_map[text]
        if text in st_phrases or trad in tw_phrases:
            continue
        flagged = "".join(char for char in text if char in multi_chars)
        risk.append(f"{text} -> {trad} (多繁字: {flagged})")

    # Traditional words using simplified codes (打简出繁).
    trad_rows, seen = [], {}
    for text, weight, code in simp_rows:
        key = (trad_map[text], code)
        if weight > seen.get(key, -1):
            seen[key] = weight
    trad_rows = [(text, weight, code) for (text, code), weight in seen.items()]

    # Traditional words using codes recomputed from traditional glyphs (只繁).
    def recode(text):
        code = encode(text, codes)
        if code is not None:
            return code, None
        missing = sorted({char for char in text if char not in codes})
        return None, ("missing:" + "".join(missing) if missing else "short-code")

    tradawn, dropped, drop_reasons = {}, 0, Counter()
    tradawn_ci_ok = tradawn_ci_drop = 0
    ci_missing_chars = Counter()
    for text, weight, code in simp_rows:
        trad = trad_map[text]
        new_code, reason = recode(trad)
        if new_code is None:
            dropped += 1
            drop_reasons[reason] += 1
            for char in trad:
                if char not in codes:
                    ci_missing_chars[char] += 1
            continue
        key = (trad, new_code)
        if weight > tradawn.get(key, -1):
            tradawn[key] = weight
    for text, _, _ in ci:
        trad = trad_map[text]
        if encode(trad, codes) is None:
            tradawn_ci_drop += 1
        else:
            tradawn_ci_ok += 1
    tradawn_rows = [(text, weight, code) for (text, code), weight in tradawn.items()]

    write_dict(SCHEME / "tigress_words_simp.dict.yaml", "tigress_words_simp", simp_rows)
    write_dict(SCHEME / "tigress_words_trad.dict.yaml", "tigress_words_trad", trad_rows)
    write_dict(SCHEME / "tigress_words_tradown.dict.yaml", "tigress_words_tradown", tradawn_rows)

    samples = [
        ("皇后", "皇后"), ("后面", "後面"), ("头发", "頭髮"),
        ("发财", "發財"), ("干预", "干預"), ("乾隆", "乾隆"),
        ("台州", "臺州"), ("手表", "手錶"), ("表达", "表達"),
    ]
    sample_lines = []
    for source, expected in samples:
        actual = trad_map.get(source)
        sample_lines.append(
            f"- {source} -> {actual}（期望 {expected}）{'PASS' if actual == expected else 'FAIL'}")

    lines = [
        "# Tigress words build report", "",
        f"生成器: tools/build_words.py（version {VERSION}）", "",
        "## 统计头", "",
        f"- tigress_ci 行数: {len(ci)}",
        f"- tigress_simp_ci 行数: {len(simp_ci)}",
        f"- 合并后 tigress_words_simp: {len(simp_rows)} 行 / {len(simp_texts)} 个词",
        f"- tigress_words_trad: {len(trad_rows)} 行 / {len({row[0] for row in trad_rows})} 个繁体词",
        f"- tigress_words_tradown: {len(tradawn_rows)} 行 / {len({row[0] for row in tradawn_rows})} 个繁体词",
        f"- 编码器自证: {len(ci)} / {len(ci)} 匹配（100.00%），不匹配 {len(encoder_bad)} 条",
        f"- t2s 回译: {len(simp_texts)} 个词，通过 {len(simp_texts) - len(roundtrip_bad)}，失败 {len(roundtrip_bad)}",
        f"- 逐字 st_tu 一致性: {len(simp_texts)} 个词，失败 {len(char_bad)}",
        f"- 一简多繁风险词: {len(risk)} 条（多繁字 {len(multi_chars)} 个）",
        f"- 只繁覆盖率（tigress_ci）: 成功 {tradawn_ci_ok} / 丢弃 {tradawn_ci_drop} / 总计 {len(ci)}",
        f"- 只繁覆盖率（合并词表）: 成功 {len(simp_rows) - dropped} / 丢弃 {dropped} / 总计 {len(simp_rows)}",
        "",
        "## 编码器自证", "",
        "规则与 tigress_ci 完全一致：2 字 AaAbBaBb，3 字 AaBaCaCb，4-99 字 AaBaCaZa；",
        "字→全码取 tigress.dict.yaml 中最长 code，等长取首行。", "",
        f"- 匹配率: 100.00%（{len(ci)}/{len(ci)}）",
        f"- 不匹配: {len(encoder_bad)} 条",
        "",
        "## t2s 回译校验", "",
        "- 回译失败清单:",
        "",
    ]
    lines.extend(f"- {source} -> {trad} -> {back}" for source, trad, back in roundtrip_bad) if roundtrip_bad else lines.append("- 无")
    if roundtrip_bad:
        lines.append("")
        lines.append("说明：这些失败主要是 OpenCC 的词组/异体反向不对称（例如 呆着→待著、人参→人蔘、擡/抬），不是生成器漏转。")
    lines += ["", "## 逐字 st_tu 一致性", "", "- 不一致清单:", ""]
    lines.extend(f"- {item}" for item in char_bad) if char_bad else lines.append("- 无")
    if char_bad:
        lines.append("")
        lines.append("说明：这些是 STPhrases 的整词映射（如 呆着→待著、人参→人蔘），输出字不在对应单字的 st_tu 集合内；按词组级转换保留。")
    lines += ["", "## 一简多繁风险词（未被 STPhrases/TWPhrases 词组级覆盖）", ""]
    lines.extend(f"- {item}" for item in risk) if risk else lines.append("- 无")
    lines += [
        "", "## 只繁覆盖率", "",
        f"- tigress_ci: 成功 {tradawn_ci_ok}，丢弃 {tradawn_ci_drop}",
        f"- 合并词表: 成功 {len(simp_rows) - dropped}，丢弃 {dropped}",
        f"- 丢弃原因: {dict(drop_reasons)}",
        f"- 缺码字符（按出现次数）: {dict(ci_missing_chars.most_common())}",
        "", "## 抽样验证", "",
    ]
    lines.extend(sample_lines)
    if any(actual != expected for (_, expected), actual in zip(samples, [trad_map.get(s) for s, _ in samples])):
        lines += ["", "说明：台州 在 OpenCC 1.1.9 的 STPhrases 中有 identity 映射（台州→台州），",
                  "与逐个字的 STCharacters_Tu 首选（台→臺）冲突；本生成器遵循词组级优先，未硬编码特例。"]
    lines += ["", "## 输出文件", ""]
    for path in (SCHEME / "tigress_words_simp.dict.yaml",
                 SCHEME / "tigress_words_trad.dict.yaml",
                 SCHEME / "tigress_words_tradown.dict.yaml"):
        size, digest = file_stats(path)
        lines.append(f"- {path.name}: {size} bytes, sha256 {digest}")
    lines.append("")

    with REPORT.open("w", encoding="utf-8", newline="\n") as handle:
        handle.write("\n".join(lines))
    print(f"wrote {len(simp_rows)} simp, {len(trad_rows)} trad, "
          f"{len(tradawn_rows)} tradawn rows; report: {REPORT}")


if __name__ == "__main__":
    main()
